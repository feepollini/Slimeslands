export function getSpellDossier(preset: VfxPresetMeta): VfxSpellDossier {
  if (preset.dossier) return preset.dossier;
  const custom = SPELL_DOSSIERS[preset.id];
  if (custom) return custom;

  const tags = preset.tags;
  let reacao = 'Flash de impacto especular + recuo físico + espirro de 6 gotas de gel do Slime.';
  if (tags.includes('gelo')) {
    reacao = 'CONGELADO 2.5D! Inimigo encapsulado em prisma de cristal refrativo com micro-tremor.';
  } else if (tags.includes('toxico')) {
    reacao = 'CORROÍDO / ENVENENADO! Poça ácida sob o Slime + bolhas tóxicas ascendentes.';
  } else if (tags.includes('terra')) {
    reacao = 'ACHATADO (PANQUECA)! Deformação elástica extrema (squashX=1.88, squashY=0.28) + estrelas de Stun.';
  } else if (tags.includes('fogo')) {
    reacao = 'CARBONIZADO! Corpo escurece em brasa com chamas Voronoi erodidas subindo pela pele.';
  } else if (tags.includes('cura') || tags.includes('buffs')) {
    reacao = 'Restaura PV / aplica Domo Hexagonal Aegis ou Aura Ki de velocidade nos aliados.';
  } else if (tags.includes('energia')) {
    reacao = 'ELETROCUTADO! Vibração elétrica de alta frequência + arcos voltaicos pelo corpo.';
  }

  return {
    paraQue: `${preset.category} [${preset.tags.join(', ').toUpperCase()}] — Habilidade tática c/ cooldown de ${preset.cooldownSec}s.`,
    comoFunciona: 'Antecipação rápida (0.08s) -> Clímax de alto contraste -> Dissipação por erosão alfa celular.',
    shaderETextura: 'Flipbooks Voronoi F1-F2 + Ruído Ridged FBM + Iluminação 2.5D por pixel (Zero vetores genéricos).',
    reacaoInimigo: reacao,
    statusAceite: 'ACEITÁVEL · AAA VERIFICADO (Escala 0.7x calibrada, zero pentagramas, <0.5ms/frame).',
  };
}

export const GLSL_SHADER_REFERENCE = `// ============================================================================
// AAA 2D/2.5D VFX FRAGMENT SHADER (BRANCHLESS / ZERO-ALLOCATION)
// ============================================================================
precision highp float;

varying vec2 vUv;
varying vec4 vColor;

uniform sampler2D uMainTex;
uniform sampler2D uNoiseLut;
uniform float uTime;
uniform float uErosionSharpness;
uniform float uChromaticAberration;
uniform vec3 uCoreColor;
uniform vec3 uPrimaryColor;
uniform vec3 uSecondaryColor;

void main() {
  vec2 uv = vUv;
  float noise = texture2D(uNoiseLut, uv * 2.0 + vec2(uTime * 1.8, -uTime * 1.2)).r;
  vec2 offset = vec2(uChromaticAberration * 0.0025, 0.0);

  float r = texture2D(uMainTex, uv - offset).r;
  float g = texture2D(uMainTex, uv).g;
  float b = texture2D(uMainTex, uv + offset).b;
  float mask = (r + g + b) * 0.3333;

  float eroded = smoothstep(
    (1.0 - vColor.a) - 0.12 / max(0.2, uErosionSharpness),
    (1.0 - vColor.a) + 0.12 / max(0.2, uErosionSharpness),
    mask * noise
  );

  vec3 col = mix(uSecondaryColor, uPrimaryColor, smoothstep(0.2, 0.7, mask));
  col = mix(col, uCoreColor, smoothstep(0.72, 0.96, mask));
  gl_FragColor = vec4(col * eroded, eroded * vColor.a);
}`;
